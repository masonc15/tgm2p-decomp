#!/usr/bin/env python3
"""Link the program with every address symbolic, so code and data can move.

The matching build (build.py) places each object at its original ROM address
and asserts it. This build links the same objects with no fixed-address
asserts: every unit of the ROM (asm segment, C object, data block) gets a
global start symbol U_<rom>, and every address the program holds is written
relative to one, so inserting bytes anywhere moves everything after it.

  asm segments    regenerated with labels for their own branches, pool loads
                  and SHC switch tables (label differences); pool words that
                  hold an address become `.long U_xxxxxx+off`
  c objects       the SHC objects from build/obj, linked as they are; their
                  undefined f_/d_/g_ names resolve to the unit symbols
  c-prefix/range  rewrapped from the SHC context object: the retained bytes
                  with its relocations re-expressed against the unit symbols
  data            the vector table, initialized RAM data and ROM data, with
                  every word classified as a pointer written as `.long`
  copy table      generated by the linker script from the section layout
  c-nonmatching   (--nonmatching) functionally equivalent C from
                  splits_nonmatching.txt in place of an asm range; only its
                  function entries exist, pool words that kept code loads from
                  the range move to a literal island at its start, and it ends
                  at its original alignment modulo 4

Two kinds of reference cannot be relocated by GNU as/ld for SH: pc-relative
instructions whose target is in another object, and addresses a C source
writes as integer literals, such as `(struct frame *)0xa7130`, which SHC emits
as unrelocated pool words. Both become fixups, which name their location and
target by unit symbols, and are applied to the linked image from its symbol
table after linking.

With no padding the image must equal the original ROM byte for byte. With
--pad ADDR:N, N filler bytes are inserted before the unit starting at ADDR
(an existing segment start in .text, any 4-aligned address in ROM data), and
the repeated filler at the end of the ROM is shortened to keep 1 MB.

usage: shiftable.py build [--pad 0xADDR:N ...] [--out DIR] [--check]
                          [--nonmatching | --nonmatching-file LIST] [--keep-size] [--text-size N]
       shiftable.py classify READS...  derive config/shiftable_pointers.json from read logs
       shiftable.py mapreads REF_LAYOUT CAND_LAYOUT REF_READS CAND_READS
"""
