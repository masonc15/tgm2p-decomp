def c_literal_words(u, insns):
    """Unrelocated pool words of a linked C unit whose value is an address."""
    out = {}
    if u.kind == "c":
        data, syms, relocs, tidx = elf_text(build.c_object(u.start, u.kind, u.arg))
        base = u.start
    else:
        stem = build.c_object(u.start, u.kind, u.arg)
        data, syms, relocs, tidx = elf_text(stem.with_suffix(".context.o"))
        base = json.loads(stem.with_suffix(".prefix.json").read_text())["context_start"]
    # any loader counts: an asm neighbour can share a C unit's pool
    for pc, i in insns.items():
        if i.pool is None or i.pool[1] != 4 or not (u.start <= i.pool[0] < u.end):
            continue
        a = i.pool[0]
        off = a - base
        if off in relocs:
            continue
        if off < 0 or off + 4 > len(data):
            continue
        v = int.from_bytes(data[off:off + 4], "big")
        if pool_pointer(v):
            out[a] = v
    return out


def plan(pads, nonmatching):
    us = units(nonmatching)
    for at, n in pads:
        if MAP.copytab <= at:
            u = split_data(us, at)
        else:
            u = next((x for x in us if x.start == at), None)
            if u is None or u.section != ".text":
                raise SystemExit(f"--pad {at:#x}: not the start of a .text unit")
        u.pad_before += n
    return us


def build_shiftable(pads, out: Path, nonmatching=False, keep_size=False, nm_file=None, text_size=None):
    out.mkdir(parents=True, exist_ok=True)
    nm_entries = read_nonmatching(nm_file) if nonmatching else None
    us = plan(pads, nm_entries)
    for u in us:
        u.keep_size = keep_size and u.kind == "c-nonmatching"
    insns, tables = code_coverage()
    want_ptr, want_int = load_overrides()
    fixups = []
    objs = []
    # pointers in code pools (asm units) and data
    pool = fn.all_pool()
    code_words = set()
    for pc in insns:
        code_words.add(pc)
    ptr_report = defaultdict(int)
    # data words are classified over the unsplit data units, so padding a
    # data unit cannot break a pointer run or hide a pointer's target
    known = known_targets(pool)
    data_ptrs = set()
    for u in units(nm_entries):
        if u.kind == "data":
            data_ptrs |= set(data_pointers(u.start, u.end, known, want_ptr, want_int))
    for u in us:
        src = out / f"{u.kind}_{u.start:06x}.s"
        if u.kind in ("asm",):
            pointers = {}
            for a in range((u.start + 3) & ~3, u.end - 3, 4):
                if a in code_words or a + 2 in code_words:
                    continue
                v = u32(a)
                t = MAP.target(v)
                if t is None or a in want_int:
                    continue
                if a in want_ptr or (a in pool and pool_pointer(v)) or t[2] in ("ram-text", "ram-data"):
                    pointers[a] = expr_for_value(us, v)
                    ptr_report["asm " + t[2]] += 1
            src.write_text(render_asm(u, us, insns, tables, fixups, pointers))
        elif u.kind == "vectors":
            pointers = {}
            for a in range(0, 0x400, 4):
                v = u32(a)
                if 0x400 <= v < MAP.text_lma:
                    pointers[a] = loc(us, v)
                elif MAP.target(v) and MAP.target(v)[2] == "ram-text":
                    pointers[a] = expr_for_value(us, v)
            src.write_text(render_data(u, pointers))
        elif u.kind == "data":
            found = [a for a in data_ptrs if u.start <= a < u.end]
            pointers = {}
            for a in found:
                pointers[a] = expr_for_value(us, u32(a))
                ptr_report[f"data {MAP.target(u32(a))[2]}"] += 1
            src.write_text(render_data(u, pointers))
        elif u.kind == "filler":
            # sized after the first link; start with the original filler
            src.write_text(render_raw(u, filler_bytes(u.end - u.start)))
        elif u.kind == "bin":
            src.write_text(render_raw(u, ROM[u.start:u.end]))
        elif u.kind == "c":
            u.obj = build.c_object(u.start, u.kind, u.arg)
            for a, v in c_literal_words(u, insns).items():
                fixups.append({"at": a, "target": None, "value": v, "kind": "abs32"})
                ptr_report["c literal"] += 1
            objs.append(u)
            continue
        elif u.kind in ("c-prefix", "c-range"):
            lits = {a: expr_for_value(us, v) for a, v in c_literal_words(u, insns).items()}
            ptr_report["c literal"] += len(lits)
            src.write_text(wrap_prefix(u, us, insns, fixups, lits))
        elif u.kind == "c-nonmatching":
            u.obj = compile_nonmatching(u, out)
            objs.append(u)
            continue
        else:
            raise SystemExit(f"unhandled unit {u}")
        o = src.with_suffix(".o")
        r = subprocess.run([*AS, "-no-pad-sections", "-o", str(o), str(src)], capture_output=True, text=True)
        if r.returncode:
            raise SystemExit(f"{src}: assembler failed:\n{r.stderr[:3000]}")
        u.obj = o
        objs.append(u)
    make_islands(us, fixups, out)
    script = linker_script(us, out, text_size)
    elf = out / "tgm2p.elf"
    image = out / "tgm2p.bin"

    def link():
        r = subprocess.run(["sh-elf-ld", "-T", str(script), "-o", str(elf)], capture_output=True, text=True)
        if r.returncode:
            raise SystemExit(f"link failed:\n{r.stderr[:4000]}")
        subprocess.run(["sh-elf-objcopy", "-O", "binary", "-j.boot", "-j.text", "-j.copytab", "-j.data",
                        "-j.rodata", str(elf), str(image)], check=True)
        return bytearray(image.read_bytes())
    data = link()
    if len(data) != ROM_SIZE:
        # padding and replaced units changed the size: refit the repeated filler
        fu = next(u for u in us if u.kind == "filler")
        n = (fu.end - fu.start) - (len(data) - ROM_SIZE)
        if n < 0:
            raise SystemExit(f"the image needs {len(data) - ROM_SIZE:#x} bytes more than the filler holds")
        src = out / f"filler_{fu.start:06x}.s"
        src.write_text(render_raw(fu, filler_bytes(n)))
        subprocess.run([*AS, "-no-pad-sections", "-o", str(fu.obj), str(src)], check=True)
        data = link()
    symbols = elf_symbols(elf)
    sections = elf_sections(elf)
    applied = apply_fixups(data, fixups, us, symbols, sections)
    image.write_bytes(bytes(data))
    layout = {"pads": [[f"0x{a:06x}", n] for a, n in pads],
              "units": [{"start": u.start, "end": u.end, "kind": u.kind, "sym": u.sym,
                         "vma": symbols.get(u.sym), "lma": lma_of(symbols.get(u.sym), sections),
                         "arg": u.arg} for u in us],
              "fixups": len(fixups), "fixups_changed": applied,
              "pointers": dict(ptr_report), "sha1": hashlib.sha1(bytes(data)).hexdigest(),
              "size": len(data)}
    (out / "layout.json").write_text(json.dumps(layout, indent=1) + "\n")
    return data, layout


def make_islands(us, fixups, out):
    """Literal islands: kept code outside a replaced range can load pool words
    that SHC placed inside it (a shared pool). Each such word is copied to an
    island at the start of the replacement unit, as a symbol expression when
    it is an address, and the load is pointed there."""
    need = defaultdict(dict)
    for f in fixups:
        if f.get("target") is None or f["kind"] not in ("mov.l", "mov.w", "mova"):
            continue
        tu = unit_of(us, f["target"])
        if tu is None or tu.kind != "c-nonmatching":
            continue
        if f["kind"] == "mova":
            raise SystemExit(f"{f['at']:#x} takes the address of {f['target']:#x} inside the replaced range "
                             f"{tu.start:#x}-{tu.end:#x} ({tu.arg})")
        need[tu.start][f["target"]] = 4 if f["kind"] == "mov.l" else 2
    for u in us:
        u.island = None
        if u.kind != "c-nonmatching" or u.start not in need:
            continue
        lines = ["\t.text", "\t.align 2"]
        for a, n in sorted(need[u.start].items(), key=lambda x: -x[1]):
            if n == 4:
                v = u32(a)
                e = expr_for_value(us, v) if pool_pointer(v) else None
                lines.append(f"__isl_{a:x}:\t.4byte\t{e if e else f'0x{v:08x}'}")
            else:
                lines.append(f"__isl_{a:x}:\t.2byte\t0x{ROM[a] << 8 | ROM[a + 1]:04x}")
        lines.append("\t.align 2")
        src = out / f"island_{u.start:06x}.s"
        src.write_text("\n".join(lines) + "\n")
        o = src.with_suffix(".o")
        r = subprocess.run([*AS, "-no-pad-sections", "-o", str(o), str(src)], capture_output=True, text=True)
        if r.returncode:
            raise SystemExit(f"{src}: assembler failed:\n{r.stderr[:3000]}")
        u.island = o


def compile_nonmatching(u, out):
    """Compile a c-nonmatching source. It may name addresses only through
    symbols (f_/d_/g_ or symbols.txt names): an address written as an integer
    would not move with the layout, so a literal-pool word that looks like a
    movable address fails the build."""
    src = ROOT / u.arg
    o = out / (Path(u.arg).stem + "_nm.o")
    flags = build.c_flags(src) or ["-macsave=1", "-optimize=1", "-speed"]
    subprocess.run([str(build.SHCC), build.SHC_VERSION, str(o), str(src), *flags], check=True)
    r = subprocess.run(["sh-elf-objdump", "-h", str(o)], capture_output=True, text=True, check=True)
    for line in r.stdout.splitlines():
        p = line.split()
        if len(p) >= 7 and p[1] in (".data", ".bss") and int(p[2], 16):
            raise SystemExit(f"{u.arg}: defines writable {p[1]} data; the game's state lives at fixed "
                             "addresses, so declare it extern as g_ symbols")
    data, syms, relocs, tidx = elf_text(o)
    for off in range(0, len(data) - 3, 2):
        w = data[off] << 8 | data[off + 1]
        if w >> 12 != 0xD:
            continue
        t = ((off + 4) & ~3) + (w & 0xFF) * 4
        if t + 4 > len(data) or t in relocs:
            continue
        v = int.from_bytes(data[t:t + 4], "big")
        if pool_pointer(v):
            raise SystemExit(f"{u.arg}: literal {v:#010x} at +{t:#x} looks like an address this build moves; "
                             "write it as an f_/d_/g_ symbol (or symbols.txt name)")
    return o


def linker_script(us, out, text_size=None):
    ld = ["SECTIONS", "{"]
    by = defaultdict(list)
    for u in us:
        by[u.section].append(u)

    def body(sec):
        lines = []
        for u in by[sec]:
            if u.kind == "filler":
                # constants of the replacement C (string literals) go to ROM
                # data, ahead of the filler that absorbs the size change
                for v in us:
                    if v.kind == "c-nonmatching":
                        lines.append(f"\t\t. = ALIGN(4); {v.obj}(.rodata)")
            if u.pad_before:
                fill = "0x0009" if sec in (".text", ".boot") else "0x00"
                lines.append(f"\t\tFILL({fill}); . = . + {u.pad_before};")
            if u.kind in ("c", "c-nonmatching"):
                lines.append(f"\t\t{u.sym} = .;")
            if getattr(u, "island", None):
                lines.append(f"\t\t{u.island}(.text)")
            lines.append(f"\t\t{u.obj}(.text {u.section})")
            if getattr(u, "keep_size", False):
                # keep the replaced range's size, so the boot copy and checksum
                # loops (and with them the game's timing) do not change
                lines.append(f"\t\tFILL(0x0009); . = {u.sym} + {u.end - u.start};")
            elif u.kind == "c-nonmatching":
                # end where the original did modulo 4, so the units after it
                # keep the alignment their pc-relative pool loads depend on
                # (the section starts 4-aligned, as ROM offsets do)
                lines.append(f"\t\tFILL(0x0009); . = . + ((0x{u.end:x} - .) & 3);")
        return lines
    ld += ["\t.boot 0 : AT(0)", "\t{"] + body(".boot") + ["\t}"]
    tail = []
    if text_size is not None:
        # a fixed code size keeps the boot copy and checksum loops, and with
        # them the frame phase the game's random sequence depends on, as they
        # were for an image of that size
        tail = ["\t\tFILL(0x0009); . = __text_start + 0x%x;" % text_size]
    ld += [f"\t.text 0x{MAP.text_vma:08x} : AT(LOADADDR(.boot) + SIZEOF(.boot))", "\t{", "\t\t__text_start = .;"] + \
        body(".text") + tail + ["\t}"]
    ld += ["\t.copytab LOADADDR(.text) + SIZEOF(.text) : AT(LOADADDR(.text) + SIZEOF(.text))", "\t{",
           "\t\t__copytab = .;",
           f"\t\tLONG(0x{MAP.bss_lo:08x}) LONG(0x{MAP.bss_hi:08x})",
           "\t\tLONG(LOADADDR(.text)) LONG(ADDR(.text)) LONG(SIZEOF(.text))",
           "\t\tLONG(LOADADDR(.data)) LONG(ADDR(.data)) LONG(SIZEOF(.data))", "\t}"]
    ld += ["\t.data ADDR(.text) + SIZEOF(.text) : AT(LOADADDR(.copytab) + SIZEOF(.copytab))", "\t{"] + \
        body(".data") + ["\t}"]
    ld += ["\t.rodata LOADADDR(.data) + SIZEOF(.data) : AT(LOADADDR(.data) + SIZEOF(.data))", "\t{"] + \
        body(".rodata") + ["\t}"]
    ld += ["\t/DISCARD/ : { *(.comment) }", "}"]
    # names the C objects leave undefined: f_/d_/g_ by address, symbols.txt by table
    for u in us:
        if u.section in (".text", ".data"):
            ld.append(f"{u.sym}_lma = LOADADDR({u.section}) + ({u.sym} - ADDR({u.section}));")
    names = c_undefined(us)
    for name in sorted(names):
        e = symbol_expr(us, name)
        if e is not None:
            ld.append(f"PROVIDE({name} = {e});")
    script = out / "rom.ld"
    script.write_text("\n".join(ld) + "\n")
    return script


def c_undefined(us):
    objs = [str(u.obj) for u in us if u.obj is not None]
    r = subprocess.run(["sh-elf-nm", "--undefined-only", *objs], capture_output=True, text=True, check=True)
    return {line.split()[-1] for line in r.stdout.splitlines() if line.strip() and not line.endswith(":")}


def symbol_expr(us, name):
    table = {}
    for line in (ROOT / "symbols.txt").read_text().splitlines():
        line = line.split("#", 1)[0].split()
        if len(line) >= 2:
            table["_" + line[0]] = int(line[1], 16)
    if name in table:
        v = table[name]
    else:
        m = re.fullmatch(r"_(f|d|g)_([0-9a-f]+)", name)
        if not m:
            return None
        v = int(m[2], 16)
        if m[1] == "f" and fn.RAM_ROM <= v < MAP.copytab:
            v += fn.RAM_BASE - fn.RAM_ROM
    t = MAP.target(v)
    if t is not None or m_boot(v):
        u = unit_of(us, t[0] if t is not None else v)
        if u is not None and u.kind == "c-nonmatching":
            return None  # the replacement object must define it
    e = expr_for_value(us, v)
    if e is None and m_boot(v):
        e = loc(us, v)
    return e if e is not None else f"0x{v:08x}"


def m_boot(v):
    return 0x400 <= v < MAP.text_lma


def elf_symbols(elf: Path) -> dict:
    r = subprocess.run(["sh-elf-nm", str(elf)], capture_output=True, text=True, check=True)
    out = {}
    for line in r.stdout.splitlines():
        p = line.split()
        if len(p) == 3:
            out[p[2]] = int(p[0], 16)
    return out


def elf_sections(elf: Path):
    r = subprocess.run(["sh-elf-objdump", "-h", str(elf)], capture_output=True, text=True, check=True)
    out = []
    for line in r.stdout.splitlines():
        p = line.split()
        if len(p) >= 7 and p[1].startswith("."):
            out.append((p[1], int(p[3], 16), int(p[4], 16), int(p[2], 16)))  # name, vma, lma, size
    return out


def lma_of(vma, sections):
    if vma is None:
        return None
    for name, v, l, size in sections:
        if v <= vma < v + max(size, 1):
            return vma - v + l
    return None


def resolve(us, symbols, a, rom=False):
    if MAP.copytab <= a < MAP.data_lma:
        return symbols["__copytab"] + a - MAP.copytab
    u = unit_of(us, a)
    if u.kind == "c-nonmatching":
        name = f"__isl_{a:x}" if f"__isl_{a:x}" in symbols else f"_f_{a:x}"
        if name not in symbols:
            raise SystemExit(f"{u.arg}: nothing defines {name}, which other code references")
        return symbols[name]
    sym = u.sym + ("_lma" if rom and u.section in (".text", ".data") else "")
    return symbols[sym] + a - u.start


def apply_fixups(data, fixups, us, symbols, sections):
    changed = 0
    for f in fixups:
        at = resolve(us, symbols, f["at"])
        pos = lma_of(at, sections)
        if f["kind"] == "abs32":
            t = MAP.target(f["value"])
            new = resolve(us, symbols, t[0], rom=t[2] == "rom-data") + (0x20000000 if t[1] else 0)
            old = int.from_bytes(data[pos:pos + 4], "big")
            data[pos:pos + 4] = new.to_bytes(4, "big")
            changed += old != new
            continue
        tgt = resolve(us, symbols, f["target"])
        w = f["insn"]
        k = f["kind"]
        if k in ("bra", "bsr"):
            d = (tgt - (at + 4)) // 2
            assert (tgt - at) % 2 == 0 and -2048 <= d < 2048, (hex(f["at"]), d)
            new = (w & 0xF000) | (d & 0xFFF)
        elif k in ("bt", "bf", "bt/s", "bf/s"):
            d = (tgt - (at + 4)) // 2
            assert -128 <= d < 128, (hex(f["at"]), d)
            new = (w & 0xFF00) | (d & 0xFF)
        elif k in ("mov.l", "mova"):
            d = tgt - ((at + 4) & ~3)
            assert d % 4 == 0 and 0 <= d < 1024, (hex(f["at"]), d)
            new = (w & 0xFF00) | (d // 4)
        elif k == "mov.w":
            d = tgt - (at + 4)
            assert d % 2 == 0 and 0 <= d < 512, (hex(f["at"]), d)
            new = (w & 0xFF00) | (d // 2)
        else:
            raise SystemExit(f"fixup kind {k}")
        old = data[pos] << 8 | data[pos + 1]
        data[pos:pos + 2] = new.to_bytes(2, "big")
        changed += old != new
    return changed


