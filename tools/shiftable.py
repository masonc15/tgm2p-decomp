def u32(a: int) -> int:
    return struct.unpack(">I", ROM[a:a + 4])[0]


# ---------------------------------------------------------------- layout facts

class Map:
    """The original memory map, read from the copy table the boot code uses."""

    def __init__(self):
        self.copytab = build.RAM_ROM_END                     # 0x313fc
        words = [u32(self.copytab + 4 * i) for i in range(8)]
        (self.bss_lo, self.bss_hi, self.text_lma, self.text_vma, self.text_size,
         self.data_lma, self.data_vma, self.data_size) = words
        assert self.text_lma == fn.RAM_ROM and self.text_vma == fn.RAM_BASE
        assert self.text_lma + self.text_size == self.copytab
        assert self.data_lma == self.copytab + 32
        self.data_end_lma = self.data_lma + self.data_size  # 0x36301
        self.rodata = (self.data_end_lma + 3) & ~3           # 0x36304
        self.filler = filler_start()                         # 0xb00ff
        self.ram_text = (self.text_vma, self.text_vma + self.text_size)
        self.ram_data = (self.data_vma, self.data_vma + self.data_size)

    def target(self, v: int):
        """Original ROM offset and cache-through flag for an address value, or
        None when the value cannot address something this build moves."""
        ct = 0
        if v >> 28 == 2:
            v, ct = v & 0x0FFFFFFF, 1
        if self.ram_text[0] <= v < self.ram_text[1]:
            return v - self.text_vma + self.text_lma, ct, "ram-text"
        if self.ram_data[0] <= v < self.ram_data[1]:
            return v - self.data_vma + self.data_lma, ct, "ram-data"
        # the ROM copy of the RAM data is read only through the copy table:
        # a value in it is an integer (216000, frames per hour, at 0xd0ec)
        if self.copytab <= v < self.data_lma or self.rodata <= v < self.filler:
            return v, ct, "rom-data"
        return None


def filler_start() -> int:
    """Start of the ROM tail that only repeats the 32 KB before it."""
    p = 0x8000
    s = len(ROM) - p
    while s > 0 and ROM[s - 1] == ROM[s - 1 + p]:
        s -= 1
    return s + p


MAP = Map()


# ---------------------------------------------------------------- units

class Unit:
    def __init__(self, start, end, kind, section, arg=None):
        self.start, self.end, self.kind, self.section, self.arg = start, end, kind, section, arg
        self.pad_before = 0
        self.obj = None

    @property
    def sym(self):
        return f"U_{self.start:06x}"

    def __repr__(self):
        return f"<{self.kind} {self.start:06x}-{self.end:06x} {self.section}>"


def segments(nonmatching=None):
    segs = list(build.read_splits())
    if nonmatching:
        segs = apply_nonmatching(segs, nonmatching)
    return segs


def apply_nonmatching(segs, entries):
    """Replace [start, end) of the map with c-nonmatching units."""
    out = []
    for a, b, kind, arg in segs:
        pieces = [(a, b, kind, arg)]
        for s, e, src in entries:
            nxt = []
            for x, y, k, g in pieces:
                if e <= x or s >= y or k == "c-nonmatching":
                    nxt.append((x, y, k, g))
                    continue
                if k not in ("asm",):
                    raise SystemExit(f"c-nonmatching {s:#x}-{e:#x} overlaps {k} segment {x:#x}-{y:#x}")
                if x < s:
                    nxt.append((x, s, k, g))
                if y > e:
                    nxt.append((e, y, k, g))
            pieces = nxt
        out += pieces
    for s, e, src in entries:
        out.append((s, e, "c-nonmatching", src))
    return sorted(out)


def read_nonmatching(path=None):
    path = path or ROOT / "splits_nonmatching.txt"
    out = []
    if path.exists():
        for line in path.read_text().splitlines():
            line = line.split("#", 1)[0].split()
            if line:
                out.append((int(line[0], 16), int(line[1], 16), line[3] if line[2] == "c-nonmatching" else None))
                if line[2] != "c-nonmatching":
                    raise SystemExit(f"{path.name}: unknown kind {line[2]}")
    return out


def units(nonmatching=None):
    out = [Unit(0, 0x400, "vectors", ".boot")]
    for a, b, kind, arg in segments(nonmatching):
        if b <= 0x400 or a >= MAP.copytab:
            continue
        section = ".boot" if a < MAP.text_lma else ".text"
        out.append(Unit(a, b, kind, section, arg))
    # data: initialized RAM data, then ROM data up to the repeated filler
    out.append(Unit(MAP.data_lma, MAP.data_end_lma, "data", ".data"))
    out.append(Unit(MAP.data_end_lma, MAP.filler, "data", ".rodata"))
    out.append(Unit(MAP.filler, ROM_SIZE, "filler", ".rodata"))
    return out


def split_data(us, at):
    """Split the data unit containing `at` so a unit starts there."""
    for i, u in enumerate(us):
        if u.start < at < u.end and u.kind == "data":
            v = Unit(at, u.end, "data", u.section)
            u.end = at
            us.insert(i + 1, v)
            return v
        if u.start == at:
            return u
    raise SystemExit(f"--pad {at:#x}: not inside a data unit or at a unit start")


def unit_of(us, a):
    for u in us:
        if u.start <= a < u.end:
            return u
    if a == MAP.copytab or (MAP.copytab <= a < MAP.data_lma):
        return None
    raise KeyError(hex(a))


def loc(us, a: int, rom=False) -> str:
    """Symbolic expression for original ROM offset a: its run-time address,
    or with rom=True its load address (differs for RAM-copied units)."""
    if MAP.copytab <= a < MAP.data_lma:
        return f"__copytab+{a - MAP.copytab}"
    u = unit_of(us, a)
    if u.kind == "c-nonmatching":
        # a replaced range has new code: only its function entries exist,
        # by name (an undefined name fails the link)
        return f"_f_{a:x}"
    off = a - u.start
    sym = u.sym + ("_lma" if rom and u.section in (".text", ".data") else "")
    return f"{sym}+{off}" if off else sym


def expr_for_value(us, v: int):
    t = MAP.target(v)
    if t is None:
        return None
    a, ct, kind = t
    # a ROM-data value inside the RAM data image addresses its ROM copy
    e = loc(us, a, rom=kind == "rom-data")
    return f"{e}+0x20000000" if ct else e


# ---------------------------------------------------------------- code discovery

def code_coverage():
    """Instruction halfwords reached by recursive descent from every entry,
    switch-table words and their targets (asm_scan's decoder)."""
    import asm_scan
    entries = asm_scan.entry_points() | set(asm_scan.c_entries()) | set(asm_scan.runtime_entries())
    insns, tables = {}, {}
    for lo, hi in ((0x400, MAP.text_lma), (MAP.text_lma, MAP.copytab)):
        for e in sorted(x for x in entries if lo <= x < hi):
            f = asm_scan.Func(e, hi, entries - {e}, lo, hi)
            for pc, i in f.insns.items():
                if i.valid:
                    insns[pc] = i
            for pc in f.insns:
                i = f.insns[pc]
                if i.mnemonic == "braf":
                    table, targets = asm_scan.switch_targets(pc, lo, hi)
                    if targets:
                        tables[table] = (pc, targets)
    return insns, tables


# ---------------------------------------------------------------- pointer classification

def round_number(v):
    """Integer-shaped ROM-data value: a multiple of 0x1000 or a mask/limit
    (0x7ffff), a pair of small signed shorts such as a (w, h) or (dx, dy)
    pair (0x00080008, 0x0008fff8), or a palette colour (6-bit R, G, B in the
    top three bytes, low byte zero: 0x00081400). None of the 145 ROM-data
    pointers the linked C objects relocate, nor any of the 167 the game was
    seen to dereference, has one of these shapes."""
    lo = v & 0xFFFF
    return v & 0xFFF in (0, 0xFFF) or lo < 0x100 or lo >= 0xFF00 or v & 0x030303FF == 0


def known_targets(pool):
    """ROM offsets the code names: targets of pointer-classified literal
    pool words and every function entry."""
    import asm_scan
    out = set(asm_scan.entry_points()) | set(asm_scan.c_entries())
    for p in pool:
        if p % 4 == 0 and p + 4 <= MAP.copytab:
            v = u32(p)
            if pool_pointer(v):
                out.add(MAP.target(v)[0])
    return out


def classify(read_logs):
    """Pointer and integer decisions for data words from MAME read logs
    (tools/replay_check.sh --reads with REPLAY_READS_SKIP_BOOT=1, ROM data and
    RAM data ranges): a word the game read and then followed (a "deref" line)
    is a pointer; a word whose bytes are read only at 8 or 16 bits is a field
    of a structure, not a pointer; a word read at 32 bits whose target is
    also read is a pointer. Everything else keeps the static rule."""
    widths = defaultdict(set)
    touched = set()
    deref = set()
    for path in read_logs:
        for line in Path(path).read_text().splitlines():
            p = line.split()
            if p[0] in ("frame", "pc"):
                continue
            if p[0] == "deref":
                a = int(p[1], 16)
                if MAP.ram_data[0] <= a < MAP.ram_data[1]:
                    a = a - MAP.data_vma + MAP.data_lma
                deref.add(a)
                continue
            a, w = int(p[0], 16), int(p[1])
            if MAP.ram_data[0] <= a < MAP.ram_data[1]:
                a = a - MAP.data_vma + MAP.data_lma
            widths[a].add(w)
            touched.update(range(a, a + w))
    entries = known_targets(fn.all_pool())
    pointer, integer = {}, {}
    for lo, hi in ((MAP.data_lma, MAP.data_end_lma), (MAP.data_end_lma, MAP.filler)):
        shaped = data_candidates(lo, hi)
        for a, t in data_candidates(lo, hi, shapes=False).items():
            r32 = 4 in widths.get(a, ())
            sub = any(w < 4 for b in range(a, a + 4) for w in widths.get(b, ()))
            if a in deref:
                pointer[a] = "read at 32 bits and followed"
            elif sub and not r32:
                integer[a] = "read only at 8/16 bits"
            elif r32 and a in shaped and t[2] in ("rom-data", "ram-data") and \
                    any(b in touched for b in range(t[0], t[0] + 4)):
                pointer[a] = "read at 32 bits, target read"
            elif r32 and a in shaped and t[2] == "ram-text" and t[0] in entries:
                pointer[a] = "read at 32 bits, target is a function entry"
    return pointer, integer


def load_overrides():
    if OVERRIDES.exists():
        d = json.loads(OVERRIDES.read_text())
        return ({int(k, 16) for k in d.get("pointer", {})}, {int(k, 16) for k in d.get("integer", {})})
    return set(), set()


def pool_pointer(v) -> bool:
    """A literal-pool word: RAM addresses always; ROM data through the
    cache-through mirror always (0x2004002c, the header pointer, sits at a
    small offset that looks like a packed pair); plain ROM data unless
    integer-shaped (flags such as 0x50000, the mask 0x7ffff, 0x000b0009)."""
    t = MAP.target(v)
    if t is None:
        return False
    if t[2] == "rom-data" and not t[1]:
        return not round_number(v & 0x0FFFFFFF)
    return True


def data_candidates(lo, hi, shapes=True):
    """Aligned words in [lo, hi) whose value could address something this
    build moves; with shapes, only those that are not integer-shaped."""
    cand = {}
    for a in range((lo + 3) & ~3, hi - 3, 4):
        v = u32(a)
        t = MAP.target(v)
        if t is None:
            continue
        if shapes and t[2] == "rom-data" and round_number(v & 0x0FFFFFFF):
            continue
        if t[2] == "ram-text" and v & 1:
            continue
        cand[a] = t
    return cand


def data_pointers(lo, hi, known_targets, want_ptr=(), want_int=()):
    """Data words taken as pointers. Run-time evidence comes first
    (config/shiftable_pointers.json, written by `shiftable.py classify`):
    words the game followed are pointers, words it reads only in parts are
    not. For the rest, a candidate that is not integer-shaped is a pointer
    when it sits next to another such candidate (a pointer table), and any
    candidate is one when its target is a function entry, an address the
    code loads, or the target of another pointer. Strided singles are not
    enough: the 12-byte sprite frame records pack dx:dy into words that look
    like ROM pointers. Returns {addr: reason}."""
    cand = data_candidates(lo, hi)
    every = data_candidates(lo, hi, shapes=False)
    out = {a: "evidence" for a in every if a in want_ptr}
    for a, t in cand.items():
        if a in want_int or a in out:
            continue
        if (a - 4 in cand) or (a + 4 in cand):
            out[a] = "run"
    named = set(known_targets) | {MAP.target(u32(a))[0] for a in out}
    for a, t in every.items():
        if a not in out and a not in want_int and t[0] in named:
            out[a] = "known-target"
    return out


# ---------------------------------------------------------------- rendering

def render_asm(u, us, insns, tables, fixups, pointers):
    """Assembly for an asm unit: labels for every in-unit branch and pool
    target, raw halfwords otherwise, absolute words as unit symbols."""
    lo, hi = u.start, u.end
    labels = set()
    code = {pc: i for pc, i in insns.items() if lo <= pc < hi}
    slot = set()
    for pc, i in code.items():
        if i.delay:
            slot.add(pc + 2)
    lines = []
    table_words = {}
    for t, (bpc, targets) in tables.items():
        if lo <= t < hi and lo <= bpc < hi:
            for k, tg in enumerate(targets):
                table_words[t + 2 * k] = (bpc, tg)
                labels.add(tg)
                labels.add(bpc + 4)
    text = {}
    for pc, i in code.items():
        if pc in slot and (i.pool or i.mova is not None):
            # a pc-relative load in a delay slot counts from the branch target
            text[pc] = f".short 0x{i.word:04x} /* {i.text()} (delay slot) */"
            continue
        tgt = None
        if i.target is not None and i.flow in ("cond", "jump", "call"):
            tgt, kind = i.target, i.mnemonic
        elif i.pool is not None:
            tgt, kind = i.pool[0], i.mnemonic
        elif i.mova is not None:
            tgt, kind = i.mova, "mova"
        if tgt is None:
            continue
        if lo <= tgt < hi and (lo % 4 == 0 or kind not in ("mov.l", "mova", "mov.w")):
            # gas computes pool alignment from the section start, so a unit
            # that starts 2 mod 4 keeps its own pool loads as raw halfwords
            labels.add(tgt)
            reg = i.ops.split(",")[-1] if (i.pool or i.mova is not None) else ""
            op = {"mov.l": f"mov.l\t.L{tgt:06x},{reg}", "mov.w": f"mov.w\t.L{tgt:06x},{reg}",
                  "mova": f"mova\t.L{tgt:06x},r0"}.get(kind, f"{kind}\t.L{tgt:06x}")
            text[pc] = op
        elif lo <= tgt < hi:
            continue
        else:
            fixups.append({"at": pc, "target": tgt, "kind": kind, "insn": i.word})
            text[pc] = f".short 0x{i.word:04x} /* {i.text()} -> fixup */"
    out = [f"/* {lo:#08x}-{hi:#08x}: generated by tools/shiftable.py */", f"\t.section {u.section},\"ax\"",
           f"\t.global {u.sym}", f"{u.sym}:"]
    pc = lo
    while pc < hi:
        if pc in labels:
            out.append(f".L{pc:06x}:")
        if pc in pointers and pc % 4 == 0 and pc + 4 <= hi and pc not in code and pc + 2 not in code:
            out.append(f"\t.4byte\t{pointers[pc]}\t/* {pc:06x}: {u32(pc):08x} */")
            if pc + 2 in labels:
                raise SystemExit(f"label inside pointer word at {pc + 2:#x}")
            pc += 4
            continue
        if pc in table_words:
            bpc, tg = table_words[pc]
            out.append(f"\t.short\t.L{tg:06x}-.L{bpc + 4:06x}\t/* {pc:06x} */")
        elif pc in text:
            out.append(f"\t{text[pc]}\t/* {pc:06x} */")
        else:
            w = fn.hw(pc)
            i = code.get(pc)
            note = f" {i.text()}" if i else ""
            out.append(f"\t.short\t0x{w:04x}\t/* {pc:06x}{note} */")
        pc += 2
    return "\n".join(out) + "\n"


def render_data(u, pointers):
    out = [f"/* {u.start:#08x}-{u.end:#08x}: generated by tools/shiftable.py */",
           f"\t.section {u.section},\"a\"", f"\t.global {u.sym}", f"{u.sym}:"]
    a = u.start
    run = bytearray()
    run_at = a

    def flush():
        nonlocal run
        for i in range(0, len(run), 16):
            chunk = run[i:i + 16]
            out.append("\t.byte\t" + ",".join(f"0x{b:02x}" for b in chunk) + f"\t/* {run_at + i:06x} */")
        run = bytearray()
    while a < u.end:
        if a in pointers and a + 4 <= u.end:
            flush()
            out.append(f"\t.4byte\t{pointers[a]}\t/* {a:06x}: {u32(a):08x} */")
            a += 4
            run_at = a
            continue
        if not run:
            run_at = a
        run.append(ROM[a])
        a += 1
    flush()
    return "\n".join(out) + "\n"


def filler_bytes(n):
    """The ROM's tail filler, which repeats a 32 KB block, cut or extended to n bytes."""
    period = 0x8000
    tail = ROM[MAP.filler:]
    out = bytearray(tail[:n])
    while len(out) < n:
        out += ROM[MAP.filler - period + (len(out) % period):MAP.filler][:n - len(out)]
    return bytes(out)


def render_raw(u, data: bytes):
    out = [f"\t.section {u.section},\"a\"", f"\t.global {u.sym}", f"{u.sym}:"]
    for i in range(0, len(data), 16):
        out.append("\t.byte\t" + ",".join(f"0x{b:02x}" for b in data[i:i + 16]))
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- C wrappers

def elf_text(obj: Path):
    from elftools.elf.elffile import ELFFile
    from elftools.elf.relocation import RelocationSection
    with obj.open("rb") as f:
        elf = ELFFile(f)
        idx = next(i for i, s in enumerate(elf.iter_sections()) if s.name == ".text")
        data = elf.get_section(idx).data()
        symtab = elf.get_section_by_name(".symtab")
        syms = [(s.name, s["st_value"], s["st_shndx"], s["st_info"]["type"], s["st_info"]["bind"])
                for s in symtab.iter_symbols()]
        relocs = {}
        for sec in elf.iter_sections():
            if isinstance(sec, RelocationSection) and sec["sh_info"] == idx:
                table = elf.get_section(sec["sh_link"])
                for r in sec.iter_relocations():
                    s = table.get_symbol(r["r_info_sym"])
                    # R_SH_DIR32 is partial-in-place: ld adds the word already
                    # in the section to r_addend, and SHC stores its offsets there
                    inplace = int.from_bytes(data[r["r_offset"]:r["r_offset"] + 4], "big")
                    add = ((r["r_addend"] if sec.is_RELA() else 0) + inplace) & 0xFFFFFFFF
                    add = add - (1 << 32) if add & 0x80000000 else add
                    relocs[r["r_offset"]] = (s.name, s["st_shndx"], s["st_value"], add, r["r_info_type"],
                                             s["st_info"]["type"])
    return data, syms, relocs, idx


def wrap_prefix(u, us, insns, fixups, literal_words):
    """Relocatable package of a c-prefix/c-range unit's retained SHC bytes."""
    stem = build.c_object(u.start, u.kind, u.arg)
    manifest = json.loads(stem.with_suffix(".prefix.json").read_text())
    cs = manifest["context_start"]
    assert manifest["start"] == u.start and manifest["end"] == u.end
    data, syms, relocs, tidx = elf_text(stem.with_suffix(".context.o"))
    kept = stem.with_suffix(".prefix.bin").read_bytes()
    lo, hi = u.start - cs, u.end - cs
    assert len(kept) == hi - lo
    lines = [f"/* {u.start:#08x}-{u.end:#08x}: {u.arg} retained SHC bytes, generated by tools/shiftable.py */",
             "\t.section .text,\"ax\"", f"\t.global {u.sym}", f"{u.sym}:"]
    exports = {}
    for name, value, shndx, typ, bind in syms:
        if shndx == tidx and typ == "STT_FUNC" and lo <= value < hi and name in manifest["functions"]:
            exports[value] = (name, bind)
    words = {}
    for off, (name, shndx, svalue, add, rtype, styp) in relocs.items():
        if not lo <= off < hi:
            continue
        if off + 4 > hi:
            raise SystemExit(f"{u.arg}: relocation straddles the retained end")
        if shndx == "SHN_UNDEF":
            words[off] = f"{name}+{add}" if add else name
        else:
            # section-relative or a defined local symbol: an address in the context
            tgt = cs + (svalue if styp == "STT_FUNC" else 0) + add
            words[off] = loc(us, tgt) if not lo <= tgt - cs < hi else f"{u.sym}+{tgt - cs - lo}"
    for a in literal_words:
        off = a - cs
        if lo <= off < hi and off not in words:
            words[off] = literal_words[a]
    off = lo
    while off < hi:
        if off in exports:
            name, bind = exports[off]
            lines += [f"\t.global {name}" if bind == "STB_GLOBAL" else f"\t.weak {name}",
                      f"\t.type {name}, @function", f"{name}:"]
        if off in words:
            lines.append(f"\t.4byte\t{words[off]}\t/* {cs + off:06x} */")
            off += 4
            continue
        w = kept[off - lo] << 8 | kept[off - lo + 1]
        pc = cs + off
        i = insns.get(pc)
        note = ""
        if i is not None and i.word == w:
            tgt = None
            if i.target is not None and i.flow in ("cond", "jump", "call"):
                tgt = i.target
            elif i.pool is not None:
                tgt = i.pool[0]
            elif i.mova is not None:
                tgt = i.mova
            if tgt is not None and not (u.start <= tgt < u.end):
                fixups.append({"at": pc, "target": tgt, "kind": i.mnemonic if i.mova is None else "mova",
                               "insn": w})
                note = " -> fixup"
            note = f" {i.text()}{note}"
        lines.append(f"\t.short\t0x{w:04x}\t/* {pc:06x}{note} */")
        off += 2
    return "\n".join(lines) + "\n"


