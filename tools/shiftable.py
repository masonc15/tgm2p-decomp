def mapreads(ref_layout, cand_layout, ref_reads, cand_reads):
    """Map both runs' read addresses back to original ROM offsets and return
    the (offset, width) keys whose read counts differ. Addresses outside every
    unit map to None."""
    import bisect

    def table(layout):
        rows = []
        for u in layout["units"]:
            for base in (u["vma"], u["lma"]):
                if base is not None:
                    rows.append((base, base + u["end"] - u["start"], u["start"]))
        rows = sorted(set(rows))
        return rows, [r[0] for r in rows]

    def load(path, rows):
        tab, starts = rows
        out = defaultdict(int)
        for line in Path(path).read_text().splitlines():
            if line.startswith(("deref", "frame", "pc ")):
                continue
            a, w, n = line.split()
            a = int(a, 16)
            i = bisect.bisect_right(starts, a) - 1
            key = None
            while i >= 0 and tab[i][0] <= a:
                if a < tab[i][1]:
                    key = tab[i][2] + a - tab[i][0]
                    break
                i -= 1
            out[(key, int(w))] += int(n)
        return out
    ref = load(ref_reads, table(ref_layout))
    cand = load(cand_reads, table(cand_layout))
    diff = [(k, ref.get(k, 0), cand.get(k, 0)) for k in set(ref) | set(cand) if ref.get(k, 0) != cand.get(k, 0)]
    return sorted(diff, key=lambda x: (x[0][0] is None, x[0][0] or 0, x[0][1]))


