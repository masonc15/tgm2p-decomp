def named_pools(text: str, local: dict = None, section_rel=frozenset(), relocs: dict = None) -> str:
    """Write each aligned pool word that holds a symbols.txt address as that
    symbol, so a ROM-rendered target carries the relocation a C object has.
    local maps addresses of the unit's own functions to their names, for
    pool words that take the address of a function in the same file; SHC
    relocates some of those against .text rather than the symbol, and the
    ROM addresses in section_rel get a local label so the target does too.
    relocs maps ROM addresses to the symbol the C object relocates that word
    against; the word is written as that symbol plus whatever offset the ROM
    value implies (a struct member or array element), if the offset is small.
    When relocs is given, words the C object doesn't relocate stay constants."""
    syms = {v: k for k, v in read_symbols().items()}
    for a, n in defined_functions().items():
        syms.setdefault(a, n)
    syms.update(local or {})
    by_name = {n: a for a, n in syms.items()}
    by_name.update(read_symbols())
    lines = text.splitlines()
    out, i = [], 0
    while i < len(lines):
        m = TAG.search(lines[i])
        if m and lines[i].lstrip().startswith(".short") and i + 1 < len(lines) \
                and lines[i + 1].lstrip().startswith(".short"):
            a = int(m[1], 16)
            v = int.from_bytes(fn.ROM[a:a + 4], "big")
            if a % 4 == 0 and a in section_rel and v in (local or {}):
                out.append(f"\t.long\t.L{local[v]}\t/* {a:06x} */")  # section-relative, as SHC wrote it
                i += 2
                continue
            if a % 4 == 0 and a in section_rel and local and 0 <= v - min(local) < 0x10000:
                # Section-relative, pointing inside a function (a jump table or
                # local data, as asmsh writes them): the unit's first label
                # plus the offset assembles to the same .text relocation.
                first = min(local)
                out.append(f"\t.long\t.L{local[first]}+{v - first}\t/* {a:06x} */")
                i += 2
                continue
            if relocs is not None and a not in relocs:
                # The C object keeps this word as a plain constant (a literal
                # hardware address, say), so the target must too.
                out.append(lines[i])
                i += 1
                continue
            # The C object's own relocation wins: another unit may name the
            # same address differently (g_6060038 vs g_6060034 + 4).
            name = (relocs or {}).get(a)
            if a % 4 == 0 and name in by_name and 0 <= v - by_name[name] < 0x1000:
                off = v - by_name[name]
                out.append(f"\t.long\t_{name}{f'+{off}' if off else ''}\t/* {a:06x} */")
                i += 2
                continue
            if a % 4 == 0 and v in syms:
                out.append(f"\t.long\t_{syms[v]}\t/* {a:06x} */")
                i += 2
                continue
            # A narrowed load (a short or byte read of a long) points a few
            # bytes into its symbol.
            base = next((v - k for k in (1, 2, 3) if a % 4 == 0 and v - k in syms), None)
            if base is not None:
                out.append(f"\t.long\t_{syms[base]}+{v - base}\t/* {a:06x} */")
                i += 2
                continue
        out.append(lines[i])
        i += 1
    return "\n".join(out) + "\n"


@functools.cache
def defined_functions() -> dict:
    """Pool-word address -> name of every function the C files define. Ones
    with real names (field_clear_flag, ...) aren't in read_symbols, but other
    units' pools point at them too."""
    out = {}
    for start, _, kind, arg in read_splits():
        obj = c_object(start, kind, arg) if kind in ("c", "c-prefix", "c-range") else None
        if obj and obj.exists():
            for a, n in c_functions(obj, start).items():
                if fn.RAM_ROM <= a < RAM_ROM_END:
                    a += fn.RAM_BASE - fn.RAM_ROM
                out[a] = n.removeprefix("_")
    return out


def name_functions(text: str, names: dict) -> str:
    """Put a global label (address -> name) on each function start that lacks one."""
    have = set(re.findall(r"^(\S+):$", text, re.M))
    out = []
    for line in text.splitlines():
        m = TAG.search(line)
        name = names.get(int(m[1], 16)) if m else None
        if name and name not in have:
            out += [f"\t.global\t{name}", f"{name}:", f".L{name.removeprefix('_')}:"]
        out.append(line)
    return "\n".join(out) + "\n"


def symbol_relocs(obj: Path) -> dict:
    """Offset in obj's .text -> the symbol (without SHC's underscore) that
    offset is relocated against, for relocations against named symbols."""
    r = subprocess.run(["sh-elf-objdump", "-r", "-j", ".text", str(obj)], capture_output=True, text=True,
                       check=True)
    out = {}
    for line in r.stdout.splitlines():
        p = line.split()
        if len(p) == 3 and p[1] == "R_SH_DIR32" and p[2].startswith("_"):
            out[int(p[0], 16)] = p[2].split("+")[0][1:]
    return out


def text_relocs(obj: Path) -> set:
    """Offsets in obj's .text whose relocation is against the .text section."""
    r = subprocess.run(["sh-elf-objdump", "-r", "-j", ".text", str(obj)], capture_output=True, text=True,
                       check=True)
    out = set()
    for line in r.stdout.splitlines():
        p = line.split()
        if len(p) == 3 and p[2].split("+")[0] == ".text":
            out.add(int(p[0], 16))
    return out


def c_functions(obj: Path, start: int) -> dict:
    nm = subprocess.run(["sh-elf-nm", "--defined-only", str(obj)], capture_output=True, text=True, check=True)
    return {start + int(a, 16): n for a, t, n in (l.split() for l in nm.stdout.splitlines()) if t in "Tt"}


def report() -> None:
    """Write objdiff.json for objdiff-cli: one unit per asm file (target only)
    and one per C file, whose target is rendered from the ROM with the C
    object's function names so objdiff can pair them."""
    segs = read_splits()
    starts = set(fn.call_targets())
    REPORT.mkdir(parents=True, exist_ok=True)
    units = []
    for a, b in asm_pieces(segs):
        names = {f: f"func_{f:06x}" for f in starts | {a} if a <= f < b}
        s = REPORT / f"{a:06x}.s"
        s.write_text(name_functions((ASM / f"{a:06x}.s").read_text(), names))
        units.append((a, {"name": f"asm/{a:06x}", "target_path": s.with_suffix(".o"),
                          "metadata": {"complete": False}}))
    for start, end, kind, arg in segs:
        if kind not in ("c", "c-prefix", "c-range"):
            continue
        src = ROOT / arg
        base = c_object(start, kind, arg)
        s = REPORT / f"{base.stem}.s"
        render_exact(start, end, set(), pool_targets(start, end), s)
        funcs = c_functions(base, start)
        # The copied block runs from RAM, so that's the address a pool holds.
        local = {a + (fn.RAM_BASE - fn.RAM_ROM if fn.RAM_ROM <= a < RAM_ROM_END else 0): n.removeprefix("_")
                 for a, n in funcs.items()}
        section_rel = {start + o for o in text_relocs(base)}
        relocs = {start + o: n for o, n in symbol_relocs(base).items()}
        s.write_text(name_functions(named_pools(s.read_text(), local, section_rel, relocs), funcs))
        unit_name = arg.removesuffix(".c") + (" (verified prefix)" if kind == "c-prefix" else
                    f" (verified range {start:#x}-{end:#x})" if kind == "c-range" else "")
        units.append((start, {"name": unit_name, "target_path": s.with_suffix(".o"),
                              "base_path": base, "metadata": {"complete": True, "source_path": arg}}))
    for _, u in units:
        # No end-of-section nop padding: a C object ending on a 2-byte
        # boundary would otherwise lose its last function to an extra nop.
        subprocess.run([*AS, "-no-pad-sections", "-o", str(u["target_path"]),
                        str(REPORT / (u["target_path"].stem + ".s"))], check=True)
    config = {
        "$schema": "https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json",
        "custom_make": "make",
        "build_target": False,
        "build_base": False,
        "units": [{k: str(v.relative_to(ROOT)) if isinstance(v, Path) else v for k, v in u.items()}
                  for _, u in sorted(units, key=lambda x: x[0])],
    }
    (ROOT / "objdiff.json").write_text(json.dumps(config, indent=2) + "\n")
    print(f"report: objdiff.json with {len(units)} units")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["split", "build", "check", "report"])
    args = ap.parse_args()
    if args.cmd == "split":
        split()
        return
    if args.cmd == "report":
        build()
        report()
        return
    ok = compare(build())
    progress()
    if args.cmd == "check" and ok:
        r = subprocess.run([sys.executable, str(ROOT / "tools" / "interleave.py"), "split",
                            str(BUILD / "tgm2p.bin"), "--check"])
        ok = r.returncode == 0
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
