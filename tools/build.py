#!/usr/bin/env python3
"""Split the program ROM into assembly/data segments and rebuild it byte-identically.

splits.txt lists where each segment starts and what builds it:

    0x000000 bin  vectors
    0x000400 asm
    0x001260 c    src/rom_header.c
    0x001278 asm
    0x002f68 c-prefix src/f_2f68.c
    0x003c88 asm
    0x0313fc bin  data

A segment runs up to the next line's address (the last one to the end of the
ROM). `asm` segments are generated by `split` from build/prog.bin, cut further
at function-group boundaries so each file stays readable. `c` segments are
compiled with SHC using the flags in the source's first-line header, and their
external symbols come from symbols.txt. `c-prefix` additionally compiles a
context-only tail but retains only a byte-verified prefix; see c_prefix.py.
`c-range` uses the same strict checks with genuine preceding context declared
by a context-rom header; only the retained range is linked or counted.
`bin` segments are .incbin'd.

usage: build.py split     regenerate asm/ and build/bin/ from build/prog.bin
       build.py build     assemble, compile, link, compare against the ROM
       build.py check     build, then split the image back into 2b.u21/1b.u22
                          and compare those against the original EPROM dumps
       build.py report    build, then write objdiff.json and the target
                          objects objdiff-cli needs for a progress report
"""
import argparse
import functools
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import fn  # noqa: E402

ROM_SIZE = 0x100000
ASM = ROOT / "asm"
BUILD = ROOT / "build"
OBJ = BUILD / "obj"
BIN = BUILD / "bin"
REPORT = BUILD / "report"
SHCC = ROOT / "tools" / "shc_probe" / "shcc.sh"
SHC_VERSION = "shc-v5.0r32"
AS = ["sh-elf-as", "--isa=sh2", "--big"]
HEADER_FLAGS = re.compile(r"flags:\s*([^*\n]+?)\s*\*/")
TAG = re.compile(r"/\* ([0-9a-f]{6}) \*/")  # the address render() puts on each line
MAX_ASM_FILE = 0x2000  # cut long asm runs at the nearest group boundary
RAM_ROM_END = 0x313fc  # end of the block the boot code copies to RAM (table at 0x313fc)


def read_splits():
    segs = []
    for line in (ROOT / "splits.txt").read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        segs.append([int(parts[0], 16), parts[1], parts[2] if len(parts) > 2 else None])
    segs.sort()
    out = []
    for i, (a, kind, arg) in enumerate(segs):
        end = segs[i + 1][0] if i + 1 < len(segs) else ROM_SIZE
        out.append((a, end, kind, arg))
    return out


AUTO_SYMBOL = re.compile(r"_(f|d|g)_([0-9a-f]+)$")


def read_symbols():
    """symbols.txt, plus every f_/d_/g_ name the compiled C objects leave
    undefined. Those names carry their address: f_<rom offset> is a function
    (seen at its RAM address when it lies in the copied block), d_<address>
    ROM data and g_<address> anything else, usually RAM."""
    syms = {}
    for line in (ROOT / "symbols.txt").read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            name, addr = line.split()[:2]
            syms[name] = int(addr, 16)
    objs = [c_object(a, kind, arg) for a, _, kind, arg in read_splits() if kind in ("c", "c-prefix", "c-range")]
    objs = [str(o) for o in objs if o.exists()]
    if objs:
        nm = subprocess.run(["sh-elf-nm", "--undefined-only", *objs], capture_output=True, text=True,
                            check=True).stdout
        for m in (AUTO_SYMBOL.match(l.split()[-1]) for l in nm.splitlines() if l.strip()):
            if m and m[0][1:] not in syms:
                a = int(m[2], 16)
                if m[1] == "f" and fn.RAM_ROM <= a < RAM_ROM_END:
                    a += fn.RAM_BASE - fn.RAM_ROM
                syms[m[0][1:]] = a
    return syms


# ---------------------------------------------------------------- split

def asm_pieces(segs):
    """Cut every asm segment into files at pool-group boundaries."""
    bounds = sorted({s for s, _, _, _ in fn.units()})
    pieces = []
    for start, end, kind, _ in segs:
        if kind != "asm":
            continue
        a = start
        while a < end:
            b = end
            if end - a > MAX_ASM_FILE:
                near = [x for x in bounds if a + 0x100 <= x <= a + MAX_ASM_FILE]
                far = [x for x in bounds if a + MAX_ASM_FILE < x < end]
                if near:
                    b = near[-1]
                elif far:
                    b = far[0]  # one group bigger than MAX_ASM_FILE
            pieces.append((a, b))
            a = b
    return pieces


def pool_targets(lo, hi):
    """Addresses read as data by pc-relative loads anywhere in [lo, hi)."""
    data = {}
    for i in fn.MD.disasm(fn.ROM[lo:hi], lo):
        if i.mnemonic in ("mov.l", "mova") and i.op_str.startswith("0x"):
            a = int(i.op_str.split(",")[0], 16)
            data[a] = data[a + 2] = True
        elif i.mnemonic == "mov.w" and i.op_str.startswith("0x"):
            data[int(i.op_str.split(",")[0], 16)] = True
    return data


def render(a0, a1, funcs, globals_, data, raw=frozenset()):
    """Assembly for [a0, a1). Lines are tagged with their address so a failed
    line can be swapped for its raw halfword on the next pass."""
    labels = set()
    body = []
    pc = a0
    while pc < a1:
        w = fn.hw(pc)
        ins = None
        if pc not in data and pc not in raw:
            ins = next(fn.MD.disasm(fn.ROM[pc:pc + 2], pc), None)
        text = None
        if ins is not None:
            op = ins.op_str.replace(" ", "")
            m = re.match(r"0x([0-9a-f]+)(.*)", op)
            if m:
                t = int(m[1], 16)
                if a0 <= t < a1:
                    labels.add(t)
                    op = f".L{t:06x}{m[2]}"
                elif ins.mnemonic in ("bsr", "bra") and t in globals_:
                    op = f"func_{t:06x}{m[2]}"
                else:
                    op = None  # target in another file: keep the raw encoding
            if op is not None:
                text = f"\t{ins.mnemonic}\t{op}" if op else f"\t{ins.mnemonic}"
        if text is None:
            text = f"\t.short\t0x{w:04x}"
        body.append((pc, text))
        pc += 2
    out = [f"/* 0x{a0:06x}-0x{a1:06x}, generated by tools/build.py split */", "\t.text"]
    by_pc = dict(body)
    for pc, text in body:
        if pc in funcs:
            out.append(f"\n\t.global\tfunc_{pc:06x}\nfunc_{pc:06x}:")
        elif pc in labels:
            out.append(f".L{pc:06x}:")
        out.append(f"{text}\t/* {pc:06x} */")
    return "\n".join(out) + "\n", by_pc


def assemble_bytes(src: Path, obj: Path):
    r = subprocess.run([*AS, "-o", str(obj), str(src)], capture_output=True, text=True)
    if r.returncode:
        return None, r.stderr
    raw = subprocess.run(["sh-elf-objcopy", "-O", "binary", "-j", ".text", str(obj), "/dev/stdout"],
                         capture_output=True, check=True).stdout
    return raw, ""


def split() -> None:
    segs = read_splits()
    ASM.mkdir(exist_ok=True)
    OBJ.mkdir(parents=True, exist_ok=True)
    BIN.mkdir(parents=True, exist_ok=True)
    for old in ASM.glob("*.s"):
        old.unlink()
    for start, end, kind, name in segs:
        if kind == "bin":
            (BIN / f"{start:06x}.bin").write_bytes(fn.ROM[start:end])
    pieces = asm_pieces(segs)
    lo = min(a for a, _ in pieces)
    hi = max(b for _, b in pieces)
    funcs = set(fn.call_targets())
    # Only functions that start in an asm file can be referenced by name.
    in_asm = {f for f in funcs if any(a <= f < b for a, b in pieces)}
    data = pool_targets(lo, hi)
    total_raw = sum(render_exact(a, b, in_asm, data, ASM / f"{a:06x}.s") for a, b in pieces)
    print(f"split: {len(pieces)} asm files, {total_raw} halfwords forced to .short")


def render_exact(a, b, funcs, data, src: Path) -> int:
    """Write [a, b) to src, forcing every line the assembler can't reproduce
    exactly to its raw halfword. Returns how many halfwords were forced."""
    raw = set()
    for _ in range(50):
        text, by_pc = render(a, b, funcs, funcs, data, frozenset(raw))
        src.write_text(text)
        got, err = assemble_bytes(src, OBJ / f"{a:06x}.chk.o")
        if got is None:
            # Can't resolve cross-file names here; they are checked at link.
            bad = set()
            for m in re.finditer(r":(\d+): Error", err):
                line = src.read_text().splitlines()[int(m[1]) - 1]
                t = TAG.search(line)
                if t:
                    bad.add(int(t[1], 16))
            if not bad:
                sys.exit(f"{src}: assembler failed:\n{err}")
            raw |= bad
            continue
        want = fn.ROM[a:b]
        # Cross-file bsr/bra to func_ symbols assemble as 0 displacement
        # before linking; only compare what the file decides by itself.
        diff = {a + o for o in range(0, len(want), 2)
                if got[o:o + 2] != want[o:o + 2]
                and not re.match(r"\t(bsr|bra)\tfunc_", by_pc.get(a + o, ""))}
        if len(got) != len(want):
            diff.add(a + min(len(got), len(want)) // 2 * 2)
        if not diff:
            break
        raw |= diff
    else:
        sys.exit(f"{src}: could not converge")
    (OBJ / f"{a:06x}.chk.o").unlink(missing_ok=True)
    return len(raw)


# ---------------------------------------------------------------- build

def c_object(start, kind, source):
    suffix = f"_{start:06x}" if kind == "c-range" else ""
    return OBJ / (Path(source).stem + suffix + ".o")


def c_context_start(src: Path) -> int:
    header = src.read_text().split("\n", 1)[0]
    m = re.search(r"\bcontext-rom:\s*(0x[0-9a-fA-F]+)\b", header)
    if not m:
        raise ValueError(f"{src}: c-range requires an explicit context-rom header")
    return int(m[1], 16)


def c_literal_tail_calls(src: Path) -> bool:
    header = src.read_text().split("\n", 1)[0]
    if "literal-tail-calls:" not in header:
        return False
    markers = re.findall(r"\bliteral-tail-calls:\s*([^\s*]+)", header)
    if markers != ["1"]:
        raise ValueError(f"{src}: literal-tail-calls must be a single explicit 1")
    return True


def c_leaf_argument_tails(src: Path) -> bool:
    header = src.read_text().split("\n", 1)[0]
    if "leaf-argument-tails:" not in header:
        return False
    markers = re.findall(r"\bleaf-argument-tails:\s*([^\s*]+)", header)
    if markers != ["1"] or not c_literal_tail_calls(src):
        raise ValueError(f"{src}: leaf-argument-tails requires one explicit 1 and literal-tail-calls: 1")
    return True


def c_field_flag_tails(src: Path) -> bool:
    header = src.read_text().split('\n', 1)[0]
    if 'field-flag-tails:' not in header:
        return False
    markers = re.findall(r'\bfield-flag-tails:\s*([^\s*]+)', header)
    if markers != ['1'] or not c_literal_tail_calls(src) or c_leaf_argument_tails(src):
        raise ValueError(f'{src}: field-flag-tails requires one explicit 1 and literal-tail-calls without leaf-argument mode')
    return True


def c_startup_reset_tails(src: Path) -> bool:
    header = src.read_text().split('\n', 1)[0]
    if 'startup-reset-tails:' not in header:
        return False
    markers = re.findall(r'\bstartup-reset-tails:\s*([^\s*]+)', header)
    if (markers != ['1'] or not c_literal_tail_calls(src) or
            c_leaf_argument_tails(src) or c_field_flag_tails(src)):
        raise ValueError(f'{src}: startup-reset-tails requires one explicit 1 and exclusive literal-tail mode')
    return True


def c_callback_tails(src: Path) -> bool:
    header = src.read_text().split('\n', 1)[0]
    if 'callback-tails:' not in header:
        return False
    markers = re.findall(r'\bcallback-tails:\s*([^\s*]+)', header)
    conflicts = ('literal-tail-calls:', 'leaf-argument-tails:', 'field-flag-tails:',
                 'startup-reset-tails:', 'guarded-switches:', 'local-loop-jumps:',
                 'function-code-range:')
    if markers != ['1'] or any(key in header for key in conflicts):
        raise ValueError(f'{src}: callback-tails requires a single exclusive 1')
    return True


def c_flags(src: Path) -> list:
    m = HEADER_FLAGS.search(src.read_text().split("\n", 1)[0])
    return m[1].split() if m else []


def c_guarded_switches(src: Path) -> bool:
    header = src.read_text().split('\n', 1)[0]
    if 'guarded-switches:' not in header:
        return False
    markers = re.findall(r'\bguarded-switches:\s*([^\s*]+)', header)
    if markers != ['1'] or c_literal_tail_calls(src) or c_leaf_argument_tails(src):
        raise ValueError(f'{src}: guarded-switches requires one explicit 1 without tail modes')
    return True


def reviewed_tail_functions():
    # Discovery can mistake literal-pool halfwords for BSR instructions.
    # Tail proofs require independently reviewed entries pinned to this ROM.
    from tail_targets import load_tail_targets
    return load_tail_targets(ROOT / "tail_targets.json", fn.ROM)


def c_local_loop_jumps(src: Path) -> bool:
    header = src.read_text().split('\n', 1)[0]
    if 'local-loop-jumps:' not in header:
        return False
    markers = re.findall(r'\blocal-loop-jumps:\s*([^\s*]+)', header)
    if markers != ['1'] or c_literal_tail_calls(src) or c_leaf_argument_tails(src) or c_guarded_switches(src):
        raise ValueError(f'{src}: local-loop-jumps requires one explicit 1 without other proof modes')
    return True


def c_function_code_range(src: Path, start: int) -> bool:
    """Select one explicit c-range whose retained bytes are the whole code CFG.

    A source can provide several ordinary ranges, so the marker names the one
    ROM start rather than silently changing every range compiled from the file.
    """
    header = src.read_text().split('\n', 1)[0]
    if 'function-code-range:' not in header:
        return False
    markers = re.findall(r'\bfunction-code-range:\s*([^\s*]+)', header)
    if len(markers) != 1:
        raise ValueError(f'{src}: function-code-range requires one explicit ROM start')
    try:
        selected = int(markers[0], 0)
    except ValueError as exc:
        raise ValueError(f'{src}: invalid function-code-range ROM start') from exc
    if selected % 2:
        raise ValueError(f'{src}: function-code-range ROM start must be aligned')
    return start == selected


def build() -> Path:
    segs = read_splits()
    OBJ.mkdir(parents=True, exist_ok=True)
    objs = []  # (start, object)
    for start, end, kind, arg in segs:
        if kind == "bin":
            s = OBJ / f"bin_{start:06x}.s"
            s.write_text(f'\t.text\n\t.incbin\t"{BIN / f"{start:06x}.bin"}"\n')
            o = OBJ / f"bin_{start:06x}.o"
            subprocess.run([*AS, "-o", str(o), str(s)], check=True)
            objs.append((start, o))
        elif kind in ("c", "c-prefix", "c-range"):
            src = ROOT / arg
            o = c_object(start, kind, arg)
            if kind in ("c-prefix", "c-range"):
                from c_prefix import compile_prefix
                # No cached pass: changing either context or its assembly-side
                # literal dependency must trigger validation on every build.
                compile_prefix(src, o, start, end, rom=fn.ROM, shcc=SHCC,
                               version=SHC_VERSION, flags=c_flags(src),
                               symbols=read_symbols(), assembler=AS,
                               context_start=c_context_start(src) if kind == "c-range" else None,
                               literal_tail_calls=c_literal_tail_calls(src),
                               leaf_argument_tails=c_leaf_argument_tails(src),
                               field_flag_tails=c_field_flag_tails(src),
                               startup_reset_tails=c_startup_reset_tails(src),
                               callback_tails=c_callback_tails(src),
                               guarded_switches=c_guarded_switches(src),
                               local_loop_jumps=c_local_loop_jumps(src),
                               function_code_range=c_function_code_range(src, start),
                               canonical_functions=reviewed_tail_functions()
                               if c_literal_tail_calls(src) else None)
            elif not o.exists() or o.stat().st_mtime < src.stat().st_mtime:
                subprocess.run([str(SHCC), SHC_VERSION, str(o), str(src), *c_flags(src)], check=True)
            objs.append((start, o))
    for s in sorted(ASM.glob("*.s")):
        a = int(s.stem, 16)
        o = OBJ / f"{s.stem}.o"
        if not o.exists() or o.stat().st_mtime < s.stat().st_mtime:
            subprocess.run([*AS, "-o", str(o), str(s)], check=True)
        objs.append((a, o))
    objs.sort()
    syms = read_symbols()

    # The boot code runs from ROM; it copies RAM_ROM..RAM_ROM_END to RAM_BASE
    # and jumps there, so that block is linked at its RAM address.
    regions = [(".boot", 0, fn.RAM_ROM, 0), (".text", fn.RAM_ROM, RAM_ROM_END, fn.RAM_BASE),
               (".rodata", RAM_ROM_END, ROM_SIZE, RAM_ROM_END)]
    ld = ["SECTIONS", "{"]
    for name, lo, hi, vma in regions:
        ld += [f"\t{name} 0x{vma:08x} : AT(0x{lo:06x})", "\t{"]
        for a, o in objs:
            if lo <= a < hi:
                at = vma + a - lo
                ld.append(f'\t\tASSERT(ABSOLUTE(.) == 0x{at:08x}, "{o.name} does not start at 0x{a:06x}");')
                ld.append(f"\t\t{o}(.text)")
        at = vma + hi - lo
        ld += [f'\t\tASSERT(ABSOLUTE(.) == 0x{at:08x}, "{name} does not end at 0x{hi:06x}");', "\t}"]
    ld += ["\t/DISCARD/ : { *(.comment) }", "}"]
    ld += [f"_{name} = 0x{addr:08x};" for name, addr in sorted(syms.items())]
    script = BUILD / "rom.ld"
    script.write_text("\n".join(ld) + "\n")
    elf = BUILD / "tgm2p.elf"
    subprocess.run(["sh-elf-ld", "-T", str(script), "-o", str(elf)], check=True)
    out = BUILD / "tgm2p.bin"
    subprocess.run(["sh-elf-objcopy", "-O", "binary", *(f"-j{r[0]}" for r in regions), str(elf), str(out)],
                   check=True)
    return out


def compare(out: Path) -> bool:
    got, want = out.read_bytes(), fn.ROM
    ok = got == want
    h = hashlib.sha1(got).hexdigest()
    if ok:
        print(f"build/tgm2p.bin OK  sha1 {h}")
    else:
        first = next((i for i in range(min(len(got), len(want))) if got[i] != want[i]), min(len(got), len(want)))
        print(f"build/tgm2p.bin MISMATCH  sha1 {h}  first diff at 0x{first:06x}  "
              f"(len 0x{len(got):x} vs 0x{len(want):x})")
    return ok


def progress() -> None:
    segs = read_splits()
    code = [(a, b, k) for a, b, k, _ in segs if k in ("asm", "c", "c-prefix", "c-range")]
    total = sum(b - a for a, b, _ in code)
    done = sum(b - a for a, b, k in code if k in ("c", "c-prefix", "c-range"))
    funcs = [f for f in fn.call_targets() if any(a <= f < b for a, b, _ in code)]
    fdone = [f for f in funcs if any(a <= f < b for a, b, k in code if k in ("c", "c-prefix", "c-range"))]
    print(f"progress: {done:#x}/{total:#x} code bytes in C ({100 * done / total:.2f}%), "
          f"{len(fdone)}/{len(funcs)} called functions")


